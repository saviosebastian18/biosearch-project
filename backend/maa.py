async def translate_text(prompt, target_language):
    """
    Translates the given English text to the target language using a text generation model.
    """
    url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-preview-05-20:generateContent?key=AIzaSyBd072S1sqaHhbeMdYSnJfrnTAk4gaG-EE"
    payload = {
        "contents": [
            {
                "parts": [
                    {
                        "text": f"Translate the following agricultural advice into {target_language} while keeping the meaning accurate and actionable. Use simple language. Here is the advice: {prompt}"
                    }
                ]
            }
        ],
        "systemInstruction": {
            "parts": [
                {
                    "text": "You are a helpful assistant for farmers. You provide clear, concise, and accurate translations of agricultural advice in regional Indian languages. Your output should be the translated text only."
                }
            ]
        }
    }

    headers = {
        'Content-Type': 'application/json'
    }

    with ThreadPoolExecutor() as pool:
        loop = asyncio.get_event_loop()
        response = await loop.run_in_executor(pool, post_request_sync, url, payload, headers)

    if response.status_code == 200:
        response_json = response.json()
        if 'candidates' in response_json and len(response_json['candidates']) > 0:
            return response_json['candidates'][0]['content']['parts'][0]['text']

    return "Translation not available."

